@Composable
fun HostelTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = AppTypography,
        shapes = AppShapes,
        content = content
    )
}

/** Rounder than the Material defaults: friendlier cards, pills and sheets. */
private val AppShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(32.dp)
)

/** Saffron → burnt orange, behind the screen headers. White text on it stays readable. */
val BrandGradient: Brush = Brush.linearGradient(listOf(BrandGradientStart, BrandGradientEnd))

/** Green used for "booked" / success states, tuned per light/dark scheme. */
val successColor: Color
    @Composable
    @ReadOnlyComposable
    get() = if (isSystemInDarkTheme()) SuccessDark else SuccessLight

val successContainerColor: Color
    @Composable
    @ReadOnlyComposable
    get() = if (isSystemInDarkTheme()) SuccessContainerDark else SuccessContainerLight

val onSuccessContainerColor: Color
    @Composable
    @ReadOnlyComposable
    get() = if (isSystemInDarkTheme()) OnSuccessContainerDark else OnSuccessContainerLight
